#!/usr/bin/env node
// Claude Code PreToolUse hook for Edit / Write / MultiEdit / NotebookEdit.
//
// Blocks edits to files that must not be changed by hand:
//   - migrations already committed under server/src/db/migrations/
//     (new, uncommitted migration files are allowed)
//   - package-lock.json files (change them through npm)
//   - .env / .env.* files except .env.example (they hold real secrets)
//
// Exit code 2 blocks the tool call and shows stderr to the agent.

import { execFileSync } from 'node:child_process';
import { basename, dirname, isAbsolute, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = process.env.CLAUDE_PROJECT_DIR
  || join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const MIGRATIONS_DIR = ['server', 'src', 'db', 'migrations'].join('/');

function isTracked(relPath, cwd) {
  try {
    execFileSync('git', ['ls-files', '--error-unmatch', '--', relPath], { cwd, stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

// Returns a reason string when the edit must be blocked, otherwise null.
export function blockReason(filePath, { root = repoRoot, tracked = isTracked } = {}) {
  if (!filePath) return null;
  const abs = isAbsolute(filePath) ? filePath : join(root, filePath);
  const rel = relative(root, abs).split(sep).join('/');
  if (rel.startsWith('..')) return null; // outside the repo
  const name = basename(rel);

  if (name === 'package-lock.json') {
    return `${rel} is generated by npm. Change dependencies with npm install/uninstall instead of editing the lockfile.`;
  }
  if ((name === '.env' || name.startsWith('.env.')) && name !== '.env.example') {
    return `${rel} holds real secrets. Edit .env.example for documented defaults, or ask the user to change ${name} themselves.`;
  }
  if (rel.startsWith(`${MIGRATIONS_DIR}/`) && tracked(rel, root)) {
    return `${rel} is an applied migration and must not be edited (CONTRIBUTING.md). Create a new one with: npm run db:migration:create --name=<snake_case>`;
  }
  return null;
}

async function main() {
  let raw = '';
  for await (const chunk of process.stdin) raw += chunk;
  let input;
  try {
    input = JSON.parse(raw);
  } catch {
    return; // not a hook payload; never block on our own parse failure
  }
  const toolInput = input.tool_input ?? {};
  const filePath = toolInput.file_path ?? toolInput.notebook_path;
  const reason = blockReason(filePath);
  if (reason) {
    process.stderr.write(`Blocked by .claude/hooks/protect-files.mjs: ${reason}\n`);
    process.exit(2);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
